/**
 * spt_attachment_reconciliation — audit retention (G2.6-H).
 *
 * Problem: 20260812140000-create-spt-attachment-reconciliation.js declared
 *   header_id -> spt_header.id  ON DELETE CASCADE.
 * Physically deleting a spt_header row therefore also deleted its
 * reconciliation rows, including the evidence that a Google Drive delete was
 * issued (DELETE_ISSUED / CLEANUP_FAILED / CLEANUP_SUCCESS). That evidence must
 * outlive the parent.
 *
 * This forward migration removes ONLY that foreign-key constraint. After it,
 * header_id remains a required (NOT NULL) historical identifier: its values are
 * preserved when a parent header is deleted, and a parent delete can no longer
 * cascade into this table.
 *
 * It does NOT touch: any column or its nullability, any index (the index that
 * backed the foreign key is kept), any status value, lease/attempt field,
 * quota table, or any row. No data is read for modification, deleted,
 * rewritten or backfilled. The historical migration is not edited.
 *
 * The constraint is NOT assumed to have a generated name. It is identified from
 * database metadata (information_schema.KEY_COLUMN_USAGE) and dropped only if it
 * is, unambiguously, a single-column foreign key
 *   spt_attachment_reconciliation.header_id -> <active database>.spt_header.id
 * Discovery is NOT limited by the referenced schema: a foreign key on header_id
 * that references a table in another schema is detected like any other. If zero
 * or several foreign keys involve header_id, if one references another schema,
 * or the match is not exactly the key above, the migration throws BEFORE
 * changing anything.
 *
 * Operational notes:
 *  - Only one DDL statement is issued, so a failure cannot leave a half-applied
 *    state. MySQL/MariaDB/TiDB DDL is not transactional in any case.
 *  - If this migration is run against a database where the foreign key does not
 *    exist (for example it was already removed by hand, or the server never
 *    recorded foreign-key metadata), it refuses to continue rather than guess.
 *    Record it in SequelizeMeta manually only after confirming the intended
 *    end state.
 *  - Because the foreign key is gone, nothing in the database now prevents a
 *    reconciliation row from referring to a header id that does not exist. That
 *    is the intended trade-off for audit retention.
 *
 * ROLLBACK (down) and its limitations:
 *  - down() re-creates the foreign key with ON DELETE CASCADE / ON UPDATE
 *    CASCADE, which RE-OPENS the audit-retention gap described above. It exists
 *    only for completeness.
 *  - down() refuses to run if any reconciliation row refers to a header id that
 *    no longer exists in spt_header (the foreign key could not be restored), and
 *    it never deletes, rewrites or backfills such rows. Resolving them is a
 *    manual decision.
 *  - down() refuses to run if any foreign key already involves header_id.
 *  - The restored constraint is named fk_spt_attachment_reconciliation_header_id;
 *    the name generated by the original migration is not known to this file and
 *    is not reproduced.
 */

const TABLE = 'spt_attachment_reconciliation';
const COLUMN = 'header_id';
const PARENT_TABLE = 'spt_header';
const PARENT_COLUMN = 'id';
const RESTORED_FK_NAME = 'fk_spt_attachment_reconciliation_header_id';

// Name of the active (default) database. The target foreign key must reference
// a table in THIS schema, so it has to be known explicitly.
async function getActiveDatabase(queryInterface, Sequelize) {
  const rows = await queryInterface.sequelize.query(
    'SELECT DATABASE() AS current_database',
    { type: Sequelize.QueryTypes.SELECT }
  );
  const name = rows && rows[0] ? rows[0].current_database : null;
  if (typeof name !== 'string' || name.trim() === '') {
    throw new Error('Refusing to continue: the active database could not be determined. Nothing was changed.');
  }
  return name;
}

// All foreign keys defined on TABLE (a child table in the active database),
// grouped by constraint name (a composite key yields several rows with one
// name). Foreign keys referencing ANOTHER schema are included, not filtered.
async function listForeignKeys(queryInterface, Sequelize) {
  const rows = await queryInterface.sequelize.query(
    `SELECT CONSTRAINT_NAME AS constraint_name,
            COLUMN_NAME AS column_name,
            REFERENCED_TABLE_SCHEMA AS referenced_schema,
            REFERENCED_TABLE_NAME AS referenced_table,
            REFERENCED_COLUMN_NAME AS referenced_column,
            ORDINAL_POSITION AS ordinal_position
       FROM information_schema.KEY_COLUMN_USAGE
      WHERE TABLE_SCHEMA = DATABASE()
        AND TABLE_NAME = :table
        AND REFERENCED_TABLE_NAME IS NOT NULL
      ORDER BY CONSTRAINT_NAME, ORDINAL_POSITION`,
    { replacements: { table: TABLE }, type: Sequelize.QueryTypes.SELECT }
  );

  const byName = new Map();
  for (const row of rows) {
    if (!byName.has(row.constraint_name)) byName.set(row.constraint_name, []);
    byName.get(row.constraint_name).push(row);
  }
  return [...byName.entries()].map(([name, columns]) => ({ name, columns }));
}

// Foreign keys that involve header_id in any way (including composite keys and
// keys that reference another schema), and the subset that is exactly the
// single-column key header_id -> <activeDatabase>.spt_header.id.
function classify(foreignKeys, activeDatabase) {
  if (typeof activeDatabase !== 'string' || activeDatabase.trim() === '') {
    throw new Error('classify() requires the active database name.');
  }
  const involvingHeaderId = foreignKeys.filter((fk) =>
    fk.columns.some((c) => c.column_name === COLUMN)
  );
  const exact = involvingHeaderId.filter(
    (fk) =>
      fk.columns.length === 1 &&
      fk.columns[0].column_name === COLUMN &&
      fk.columns[0].referenced_schema === activeDatabase &&
      fk.columns[0].referenced_table === PARENT_TABLE &&
      fk.columns[0].referenced_column === PARENT_COLUMN
  );
  return { involvingHeaderId, exact };
}

function describe(foreignKeys) {
  if (foreignKeys.length === 0) return '(none)';
  return foreignKeys
    .map(
      (fk) =>
        `${fk.name}: ` +
        fk.columns
          .map((c) => `${c.column_name} -> ${c.referenced_schema}.${c.referenced_table}.${c.referenced_column}`)
          .join(', ')
    )
    .join('; ');
}

module.exports = {
  async up(queryInterface, Sequelize) {
    const quote = (identifier) => queryInterface.queryGenerator.quoteIdentifier(identifier);

    const activeDatabase = await getActiveDatabase(queryInterface, Sequelize);
    const before = await listForeignKeys(queryInterface, Sequelize);
    const { involvingHeaderId, exact } = classify(before, activeDatabase);

    if (involvingHeaderId.length !== 1 || exact.length !== 1) {
      throw new Error(
        `Refusing to drop a foreign key from ${TABLE}: expected exactly one single-column foreign key ` +
          `${COLUMN} -> ${PARENT_TABLE}.${PARENT_COLUMN} and no other foreign key involving ${COLUMN}. ` +
          `Found on ${COLUMN}: ${describe(involvingHeaderId)}. All foreign keys on ${TABLE}: ${describe(before)}. ` +
          `Nothing was changed.`
      );
    }

    const constraintName = exact[0].name;
    if (typeof constraintName !== 'string' || constraintName.trim() === '') {
      throw new Error(`Refusing to continue: the foreign key on ${TABLE}.${COLUMN} has no usable name in metadata. Nothing was changed.`);
    }

    // The single DDL statement of this migration. The name comes from metadata
    // and is quoted as an identifier.
    await queryInterface.sequelize.query(
      `ALTER TABLE ${quote(TABLE)} DROP FOREIGN KEY ${quote(constraintName)}`
    );

    // Read-only confirmation that the key is gone (nothing else was changed).
    const after = await listForeignKeys(queryInterface, Sequelize);
    if (classify(after, activeDatabase).involvingHeaderId.length !== 0) {
      throw new Error(
        `The foreign key on ${TABLE}.${COLUMN} is still present after DROP FOREIGN KEY ` +
          `(${describe(classify(after, activeDatabase).involvingHeaderId)}). Inspect the database manually.`
      );
    }
  },

  async down(queryInterface, Sequelize) {
    const quote = (identifier) => queryInterface.queryGenerator.quoteIdentifier(identifier);

    const activeDatabase = await getActiveDatabase(queryInterface, Sequelize);
    const existing = await listForeignKeys(queryInterface, Sequelize);
    const { involvingHeaderId } = classify(existing, activeDatabase);
    if (involvingHeaderId.length !== 0) {
      throw new Error(
        `Refusing to restore the foreign key: ${TABLE}.${COLUMN} is already involved in ` +
          `${describe(involvingHeaderId)}. Nothing was changed.`
      );
    }

    // The restored key would fail (and must not be forced) if history refers to
    // headers that no longer exist. Rows are never deleted or rewritten here.
    const [{ orphan_count: orphanCount }] = await queryInterface.sequelize.query(
      `SELECT COUNT(*) AS orphan_count
         FROM ${quote(TABLE)} r
         LEFT JOIN ${quote(PARENT_TABLE)} h ON h.${quote(PARENT_COLUMN)} = r.${quote(COLUMN)}
        WHERE h.${quote(PARENT_COLUMN)} IS NULL`,
      { type: Sequelize.QueryTypes.SELECT }
    );
    if (Number(orphanCount) > 0) {
      throw new Error(
        `Cannot restore the foreign key: ${orphanCount} row(s) in ${TABLE} refer to a ${PARENT_TABLE} id that ` +
          `no longer exists. These rows are audit history and were not modified; resolve them manually if the ` +
          `rollback is really intended. Nothing was changed.`
      );
    }

    await queryInterface.addConstraint(TABLE, {
      fields: [COLUMN],
      type: 'foreign key',
      name: RESTORED_FK_NAME,
      references: { table: PARENT_TABLE, field: PARENT_COLUMN },
      onUpdate: 'CASCADE',
      onDelete: 'CASCADE',
    });
  },
};
